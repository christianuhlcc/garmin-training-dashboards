// Builds site/static/body.svg from the muscle artwork in react-native-body-highlighter (MIT, © 2022 ELABBASSI Hicham).
// Only path data is used; region ids are the keys of src/exercise_map.yaml `regions` (tested).
//
//   mkdir -p /tmp/rnbh && cd /tmp/rnbh && npm pack react-native-body-highlighter@3.2.0 && tar xzf *.tgz
//   node tools/make_body_svg.cjs /tmp/rnbh/package > site/static/body.svg
"use strict";
const pkg = process.argv[2];
if (!pkg) { console.error("usage: node tools/make_body_svg.cjs <react-native-body-highlighter package dir>"); process.exit(1); }
const front = require(pkg + "/dist/assets/bodyFront.js").bodyFront;
const back = require(pkg + "/dist/assets/bodyBack.js").bodyBack;

const LABELS = {
  chest: "Chest", front_delts: "Front delts", side_delts: "Side delts", biceps: "Biceps", forearms: "Forearms", abs: "Abs",
  obliques: "Obliques", quads: "Quads", adductors: "Adductors", calves: "Calves", traps: "Traps", rear_delts: "Rear delts",
  lats: "Lats", upper_back: "Upper back", lower_back: "Lower back", triceps: "Triceps", glutes: "Glutes", hamstrings: "Hamstrings",
};
// slug (+ optional piece index) -> region. Unlisted slugs (head, hands, knees, tibialis, ...) are drawn as neutral silhouette.
const FRONT = { chest: "chest", deltoids: "front_delts", biceps: "biceps", triceps: "triceps", forearm: "forearms", abs: "abs",
  obliques: "obliques", quadriceps: "quads", adductors: "adductors", calves: "calves", trapezius: "traps" };
const BACK = { trapezius: "traps", deltoids: "rear_delts", triceps: "triceps", forearm: "forearms", gluteal: "glutes",
  hamstring: "hamstrings", adductors: "adductors", calves: "calves",
  // piece order differs per side: the latissimus is left[1] / right[2], the erectors left[1] / right[0];
  // the other upper-back pieces are infraspinatus / teres, the other lower-back piece is the obliques seen from behind
  "upper-back": (i, side) => (i === (side === "right" ? 2 : 1) ? "lats" : "upper_back"),
  "lower-back": (i, side) => (i === (side === "right" ? 0 : 1) ? "lower_back" : "obliques") };

// The front deltoid is one shape; its outer ~40 % is the lateral head (side delts). Split with clip rects (artwork coords).
const CLIPS = `<defs><clipPath id="bm-side"><rect x="0" y="280" width="226" height="140"/><rect x="501" y="280" width="250" height="140"/></clipPath>` +
  `<clipPath id="bm-front"><rect x="226" y="280" width="275" height="140"/></clipPath></defs>`;

function pieces(m) {
  // [{d, i, side}] with i = piece index within that side
  const out = [];
  for (const side of ["common", "left", "right"]) (m.path[side] || []).forEach((d, i) => out.push({ d, i, side }));
  return out;
}

function view(data, map, dx, label, cx, primary) {
  const neutral = [], regions = {};
  const add = (r, p) => (regions[r] = regions[r] || []).push(p);
  for (const m of data) {
    const rule = map[m.slug];
    for (const { d, i, side } of pieces(m)) {
      if (!rule) { neutral.push(`<path d="${d}"/>`); continue; }
      const r = typeof rule === "function" ? rule(i, side) : rule;
      if (m.slug === "deltoids" && map === FRONT) {
        add("front_delts", `<path d="${d}" clip-path="url(#bm-front)"/>`);
        add("side_delts", `<path d="${d}" clip-path="url(#bm-side)"/>`);
      } else add(r, `<path d="${d}"/>`);
    }
  }
  const groups = Object.entries(regions).map(([r, ps]) => {
    const tab = primary.has(r) ? "-1" : "0";  // a muscle drawn in both views is one tab stop
    primary.add(r);
    return `<g class="region" data-muscle="${r}" tabindex="${tab}" role="button" aria-label="${LABELS[r]}">${ps.join("")}</g>`;
  });
  return `<g class="view" transform="translate(${dx},-86)"><g class="neutral">${neutral.join("")}</g>${groups.join("")}` +
    `<text class="view-label" x="${cx}" y="1328">${label}</text></g>`;
}

const seen = new Set();
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1310 1250" class="body-map" aria-label="Muscle map, front and back">
<!-- Muscle artwork: react-native-body-highlighter 3.2.0, MIT License, Copyright (c) 2022 ELABBASSI Hicham. Generated by tools/make_body_svg.cjs. -->
${CLIPS}
${view(front, FRONT, -43, "Front", 364, seen)}
${view(back, BACK, -762 + 668, "Back", 1083, seen)}
</svg>
`;
for (const r of Object.keys(LABELS)) if (!svg.includes(`data-muscle="${r}"`)) { console.error("missing region " + r); process.exit(1); }
process.stdout.write(svg);
